export const PROJECT_MAP = Object.fromEntries(PROJECTS.map((p) => [p.id, p]));

/**
 * The best catalog project for a skill: one where it's a primary skill,
 * preferring projects relevant to the role. Returns null if none fit.
 */
export const projectForSkill = (skillId, roleId) => {
  const primary = PROJECTS.filter((p) => p.primary.includes(skillId));
  if (!primary.length) return null;
  return primary.find((p) => p.roles.includes(roleId)) || primary[0];
};
