export const SKILL_MAP = Object.fromEntries(SKILLS.map((skill) => [skill.id, skill]));

const normalize = (value) => value.toLowerCase().replace(/\s+/g, ' ').trim();

const NAME_INDEX = (() => {
  const index = new Map();
  for (const skill of SKILLS) {
    index.set(normalize(skill.name), skill.id);
    index.set(normalize(skill.id), skill.id);
    for (const alias of skill.aliases || []) {
      if (!index.has(normalize(alias))) index.set(normalize(alias), skill.id);
    }
  }
  return index;
})();

export const slugify = (value) =>
  normalize(value)
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);

/** Find a catalog skill by display name or alias. Returns the skill or null. */
export const findSkillByName = (name) => {
  if (!name) return null;
  const id = NAME_INDEX.get(normalize(name));
  return id ? SKILL_MAP[id] : null;
};

/** Skills the user typed that aren't in the catalog get a generic definition. */
export const makeCustomSkill = (name) => ({
  id: `custom:${slugify(name)}`,
  name: name.trim(),
  category: 'Custom',
  custom: true,
  prerequisites: [],
  hours: 20,
  why: `${name.trim()} is part of the skill set you chose for this role.`,
  topics: ['Core concepts', 'Hands-on practice', 'Common tools and workflows', 'Applying it in a project'],
  advanced: ['Advanced patterns'],
  practice: 'Complete 10 hands-on exercises',
  project: `Build a small project that uses ${name.trim()}`,
  resources: [],
});

/** Resolve any skill id, including custom ones. */
export const getSkill = (id, fallbackName) => {
  if (SKILL_MAP[id]) return SKILL_MAP[id];
  if (id?.startsWith('custom:')) return makeCustomSkill(fallbackName || id.slice(7).replace(/-/g, ' '));
  return null;
};

/** Build a search link for resource suggestions that don't carry a verified URL. */
export const searchUrlFor = (type, query) => {
  const q = encodeURIComponent(query);
  if (type === 'video') return `https://www.youtube.com/results?search_query=${q}`;
  return `https://www.google.com/search?q=${q}`;
};
