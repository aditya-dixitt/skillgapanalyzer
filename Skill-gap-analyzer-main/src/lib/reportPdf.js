/**
 * Downloadable career-readiness report (text-based PDF via jsPDF).
 */

import { explainReadiness, READINESS_DISCLAIMER } from './readiness.js';
import { evidenceSummary } from './evidence.js';
import { pdfSafe } from './resumeExport.js';

export const buildReadinessReport = async ({ name, role, analysis, evidence, portfolio, now = new Date() }) => {
  const { jsPDF } = await import('jspdf');
  const ex = explainReadiness(analysis, role);
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const M = 48;
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  let y = M;

  const ensure = (h) => {
    if (y + h > H - M) {
      doc.addPage();
      y = M;
    }
  };
  const text = (value, { size = 10, style = 'normal', color = 17, x = M, width = W - 2 * M, gap = 1.35 } = {}) => {
    doc.setFont('helvetica', style);
    doc.setFontSize(size);
    doc.setTextColor(color);
    for (const line of doc.splitTextToSize(pdfSafe(value), width)) {
      ensure(size * gap);
      y += size;
      doc.text(line, x, y);
      y += size * (gap - 1);
    }
  };
  const heading = (value) => {
    y += 14;
    ensure(28);
    text(value.toUpperCase(), { size: 10, style: 'bold', color: 60 });
    doc.setDrawColor(200);
    doc.line(M, y + 3, W - M, y + 3);
    y += 8;
  };
  const row = (left, right, { bold = false } = {}) => {
    ensure(15);
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(17);
    const lines = doc.splitTextToSize(pdfSafe(left), W - 2 * M - 120);
    doc.text(lines[0], M, y + 10);
    doc.text(pdfSafe(right), W - M, y + 10, { align: 'right' });
    y += 14;
  };

  text('Career readiness report', { size: 20, style: 'bold' });
  text(`${name || 'SkillGap user'} · ${now.toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })}`, { size: 10, color: 90 });

  heading('Target role');
  text(`${ex.profile.roleName}${ex.profile.company ? ` at ${ex.profile.company}` : ''}`, { size: 12, style: 'bold' });
  text(`Readiness: ${ex.score}/100 · ${ex.matched.length} matched, ${ex.partial.length} partial, ${ex.missing.length} missing of ${ex.rows.length} requirements`, { size: 10 });
  if (ex.profile.version) text(`Role profile version ${ex.profile.version}, last reviewed ${ex.profile.reviewedAt}.`, { size: 9, color: 90 });
  text(READINESS_DISCLAIMER, { size: 8.5, color: 110 });

  heading('How the score is calculated');
  text('Each requirement is weighted by importance (Critical 4, High 3, Medium 2, Low 1). You earn its points in proportion to how close your level is to the target, capped at 100%.', { size: 9.5 });
  y += 4;
  row('Requirement', 'You / target · points', { bold: true });
  for (const r of ex.rows) row(`${r.label} (${r.importanceLabel})`, `${r.current}% / ${r.required}% · ${r.pointsEarned}/${r.pointsMax}`);

  heading('Most important next steps');
  const next = analysis.blockers.slice(0, 5);
  if (next.length) for (const b of next) text(`• ${b.skillName}: ${b.current}% → ${b.required}% (worth up to +${b.pointsAvailable} points)`, { size: 10 });
  else text('No gaps left for this role.', { size: 10 });

  heading('Evidence behind your skills');
  const counts = evidenceSummary(evidence, analysis.items.map((i) => i.skillId));
  text(`Practically assessed: ${counts.practical} · Quiz-assessed: ${counts.quiz} · Project-supported: ${counts.project} · Self-reported: ${counts.self} · No evidence: ${counts.none}`, { size: 10 });
  text('Only practical challenges and passed assessments count as verified. Self-reported levels are the user’s own estimates.', { size: 8.5, color: 110 });

  if (portfolio?.projects?.length) {
    heading('Completed projects');
    for (const p of portfolio.projects) text(`• ${p.title}${p.skills.length ? ` — ${p.skills.join(', ')}` : ''}`, { size: 10 });
  }
  if (portfolio?.assessments) {
    heading('Verified results');
    for (const q of portfolio.assessments.quizzes) text(`• ${q.skill} assessment: ${q.pct}% (${q.date})`, { size: 10 });
    for (const p of portfolio.assessments.practical) text(`• Practical: ${p.title} (${p.skill}, ${p.difficulty}, ${p.date})`, { size: 10 });
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i += 1) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(140);
    doc.text(pdfSafe(`Generated by SkillGap · page ${i} of ${pages}`), W / 2, H - 24, { align: 'center' });
  }
  return doc.output('arraybuffer');
};
